def resolve_team_name(name):
    """
    Takes a team name (in any format) and returns the standardized three-letter code.
    Returns None if the name is not found in the mapping.
    """
    if pd.isna(name):
        return None
    name_str = str(name).strip()

    # If the input is already a known team code (common in lineup feeds),
    # return it directly.
    code_upper = name_str.upper()
    if code_upper in soccer_teams.values():
        return code_upper

    return soccer_teams.get(name_str)


def resolve_team_name_fuzzy(name):
    """
    Enhanced version that tries multiple matching strategies:
    1. Exact match in the dictionary
    2. Case-insensitive match
    3. Normalized match (removing common suffixes/prefixes)
    """
    if pd.isna(name):
        return None
    
    name_str = str(name).strip()

    # Fast-path for already standardized team codes.
    code_upper = name_str.upper()
    if code_upper in soccer_teams.values():
        return code_upper
    
    # 1. Direct lookup
    result = soccer_teams.get(name_str)
    if result:
        return result
    
    # 2. Case-insensitive lookup
    name_lower = name_str.lower()
    for key, value in soccer_teams.items():
        if key.lower() == name_lower:
            return value
    
    # 3. Try removing common suffixes
    for suffix in [' FC', ' CF', ' SC', ' S.A.D.', ' S. A. D.', ' Football Club']:
        if name_str.endswith(suffix):
            shortened = name_str[:-len(suffix)].strip()
            result = soccer_teams.get(shortened)
            if result:
                return result
    
    # 4. Try removing common prefixes
    for prefix in ['FC ', 'AC ', 'AS ', 'SD ', 'CD ', 'SC ', 'UD ', '1. ']:
        if name_str.startswith(prefix):
            shortened = name_str[len(prefix):].strip()
            result = soccer_teams.get(shortened)
            if result:
                return result
    
    return None


def get_full_name_from_code(code):
    """
    Reverse lookup: find a full team name from a three-letter code.
    Returns the first matching full name found.
    """
    if pd.isna(code):
        return None
    
    code_str = str(code).strip().upper()
    
    # Find all full names that map to this code
    matching_names = []
    for full_name, team_code in soccer_teams.items():
        if team_code.upper() == code_str:
            matching_names.append(full_name)
    
    if matching_names:
        # Prefer names from the xG list (third list) as they're most common
        # Then prefer shorter names
        return min(matching_names, key=len)
    
    return None